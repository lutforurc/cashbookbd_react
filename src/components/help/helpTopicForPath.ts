export const helpTopicForPath = (pathname: string): string | null => {
  if (HELP_ROUTE_TOPICS[pathname]) return HELP_ROUTE_TOPICS[pathname];

  // An edit screen is one path with an id in it; the map stores the pattern.
  const segments = pathname.split('/').filter(Boolean);

  for (const [pattern, topic] of Object.entries(HELP_ROUTE_TOPICS)) {
    if (!pattern.includes(':')) continue;

    const parts = pattern.split('/').filter(Boolean);

    if (parts.length === segments.length && parts.every((part, index) => part.startsWith(':') || part === segments[index])) {
      return topic;
    }
  }

  return null;
};
