    const digitsRef = React.useRef<HTMLDivElement>(null);
    useLocalDigits(digitsRef, (i18n.language || 'en') !== 'en');
    const safeRows: EmployeeRow[] = Array.isArray(rows) ? rows : [];

    /**
     * The earning columns, in the order the server priced them — the same rule
     * the Generate screen uses (ComponentSalaryGenerate's `earningColumns`), so
     * the paper and the screen can never disagree.
     *
     * ⚠️ BUILT FROM THE ROWS, NOT THE PAY-HEAD MASTER: a pay head nobody on
     * this sheet has must not take a column. Empty for a sheet from the old
     * fixed engine (it carries no `components`), and the table below then draws
     * its original fixed columns exactly as before.
     *
     * A hook, so it sits above every return — this component has none today,
     * but the rule is the rule.
     */
    const earningColumns = React.useMemo(() => {
      const seen = new Map<string, string>();

      safeRows.forEach((row) => {
        (row.components || []).forEach((line) => {
          if (line.component_type === 'earning' && line.component_code && !seen.has(line.component_code)) {
            // The pay head's Bangla name on a Bangla sheet, where it has one.
            seen.set(
              line.component_code,
              (i18n.language !== 'en' && line.component_name_local) || line.component_name || line.component_code,
            );
          }
        });
      });

      return Array.from(seen.entries()).map(([code, name]) => ({ code, name }));
    }, [safeRows]);

    const amountOf = (row: EmployeeRow, code: string) =>
      Number((row.components || []).find((line) => line.component_code === code)?.amount ?? 0);

